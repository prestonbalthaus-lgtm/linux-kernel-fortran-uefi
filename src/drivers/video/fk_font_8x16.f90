!> The 8x16 bitmap font (roadmap 2.3).
!!
!! WHERE THESE 4096 BYTES COME FROM, AND WHY THAT MATTERS
!!
!! They are NOT hand-transcribed and NOT invented.  tools/gen-font-8x16.py
!! reads them out of vendor/linux-<ver>/lib/fonts/font_8x16.c -- the same
!! GPL-2.0 file the kernel compiles into font_vga_8x16 -- and rewrites the
!! region between the BEGIN/END markers below.  Re-running the generator on an
!! unchanged input is a no-op, so `git diff --exit-code` after a run proves the
!! checked-in table is genuine rather than plausible.
!!
!! That provenance is the whole point.  A 4096-byte table of hex is exactly the
!! kind of artefact nobody proofreads: one wrong byte is one wrong pixel row in
!! one glyph, invisible until somebody happens to print that character.  Because
!! the table is generated from the kernel's own font, it also gets a real
!! differential oracle: tests/drivers/video/test_gop_renderer.c compares all
!! 4096 bytes against the COMPILED font_vga_8x16 object, so a single flipped bit
!! fails the build.
!!
!! ALL 256 GLYPHS, NOT 128.  The low half is ASCII; the high half is the IBM
!! code page 437 box-drawing and symbol range that the kernel's console font
!! carries.  Keeping the upper half costs 2 KiB of .rodata and means the table
!! is a straight copy of its source -- truncating it to 128 would introduce a
!! difference between this file and its oracle for no benefit.
!!
!! WHY THIS IS ITS OWN MODULE
!!
!! It was originally inlined in fk_gop_renderer.f90.  Font DATA and the
!! renderer that walks it are separate concerns: a serial console (roadmap 2.1)
!! or a future framebuffer console has no reason to drag in the renderer to get
!! at a glyph, and the renderer has no reason to be recompiled when the font is
!! regenerated.
!!
!! THE TABLE IS PRIVATE, AND THE ACCESSOR IS THE INTERFACE.  This is not
!! encapsulation for its own sake -- it is a size constraint.  FONT_8X16 is a
!! PARAMETER, and gfortran materialises a parameter array into the .rodata of
!! every object that indexes it.  If the renderer indexed the array directly,
!! the linked kernel would carry TWO copies: 8 KiB of image for 4 KiB of font.
!! Every consumer therefore goes through vga_font_row(), so exactly one object
!! contains the table and the linked image has one 4096-byte symbol.
!! tools/linkscript-test.sh asserts that symbol lands in .rodata.
!!
!! SIGNED BYTES.  Fortran has no unsigned types, so each byte is stored
!! PRE-BIASED into the c_int8_t of identical bit pattern (0xFF -> -1) and
!! unmasked with IAND(..., 255) on the way out, exactly as fk_bcd does for u8.
