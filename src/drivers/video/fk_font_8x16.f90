  !> One row of one glyph, as 8 bits with the LEFTMOST pixel in bit 7.
  !!
  !! ch   glyph index, 0..255
  !! row  scanline within the glyph, 0..15
  !!
  !! Returns -1 for an out-of-range request, which is distinguishable from every
  !! real row (rows are 0..255).  Exported over the C ABI so the differential
  !! test can compare all 4096 bytes against the compiled kernel font object,
  !! and so that C callers -- a future console -- need no Fortran module.
  function vga_font_row(ch, row) result(bits) bind(c, name="vga_font_row")
    implicit none
    integer(c_int32_t), intent(in), value :: ch, row
    integer(c_int32_t)                    :: bits

    if (ch < 0_c_int32_t .or. ch >= FONT_GLYPHS) then
       bits = -1_c_int32_t
       return
    end if
    if (row < 0_c_int32_t .or. row >= FONT_H) then
       bits = -1_c_int32_t
       return
    end if

    ! Undo the c_int8_t sign bias: IAND against 255 recovers the byte exactly
    ! as fk__bcd2bin does for its unsigned char argument.
    bits = iand(int(FONT_8X16(ch * FONT_H + row), c_int32_t), 255_c_int32_t)
  end function vga_font_row

